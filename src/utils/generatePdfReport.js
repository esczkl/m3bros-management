import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { BRANCHES, PAYMENT_MODES } from '../config/constants';

// Color palette
const BLUE = [37, 99, 235];
const DARK = [31, 41, 55];
const GRAY = [107, 114, 128];
const GREEN = [22, 163, 74];
const RED = [220, 38, 38];
const WHITE = [255, 255, 255];
const LIGHT_BLUE = [239, 246, 255];
const LIGHT_GRAY = [249, 250, 251];

const PHP = (n) => `PHP ${Number(n).toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

const formatDate = (dateStr) => {
  const d = new Date(dateStr + 'T00:00:00');
  return d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
};

export function generatePdfReport({
  exportBranch,
  dateRange,
  transactions,
  inventoryLogs,
  getBranchStats,
  getSummaryStats,
}) {
  const doc = new jsPDF('p', 'mm', 'a4');
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const margin = 14;
  const contentW = pageW - margin * 2;
  let y = margin;

  const isAll = exportBranch === 'all';
  const reportStats = isAll ? getSummaryStats() : getBranchStats(exportBranch);
  const branchLabel = isAll ? 'All Branches' : BRANCHES[exportBranch].name;

  // Filtered data
  const filteredTxs = isAll
    ? Object.values(transactions).flat().filter(t => t.date >= dateRange.start && t.date <= dateRange.end)
    : (transactions[exportBranch] || []).filter(t => t.date >= dateRange.start && t.date <= dateRange.end);

  const filteredExpenses = isAll
    ? inventoryLogs.filter(i => i.date >= dateRange.start && i.date <= dateRange.end)
    : inventoryLogs.filter(i => i.branch === exportBranch && i.date >= dateRange.start && i.date <= dateRange.end);

  // Staff earnings (sorted by total desc)
  const staffMap = {};
  filteredTxs.forEach(tx => {
    if (!staffMap[tx.staff]) staffMap[tx.staff] = { name: tx.staff, total: 0, count: 0 };
    staffMap[tx.staff].total += tx.staffCut || 0;
    staffMap[tx.staff].count += 1;
  });
  const staffEarnings = Object.values(staffMap).sort((a, b) => b.total - a.total);

  // Payment breakdown
  const paymentMap = {};
  let paymentGrandTotal = 0;
  PAYMENT_MODES.forEach(m => { paymentMap[m] = { count: 0, amount: 0 }; });
  filteredTxs.forEach(tx => {
    const mode = tx.paymentMode || 'Cash';
    if (!paymentMap[mode]) paymentMap[mode] = { count: 0, amount: 0 };
    paymentMap[mode].count += 1;
    paymentMap[mode].amount += tx.price || 0;
    paymentGrandTotal += tx.price || 0;
  });

  // ===== FOOTER HELPER =====
  const addFooter = () => {
    const pageCount = doc.internal.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      doc.setPage(i);
      doc.setFontSize(7);
      doc.setTextColor(...GRAY);
      doc.text(`Page ${i} of ${pageCount}`, pageW / 2, pageH - 6, { align: 'center' });
      doc.text('Generated by M3 Bros Management System V2.5', margin, pageH - 6);
      doc.text('CONFIDENTIAL', pageW - margin, pageH - 6, { align: 'right' });
      // thin line
      doc.setDrawColor(...GRAY);
      doc.setLineWidth(0.2);
      doc.line(margin, pageH - 10, pageW - margin, pageH - 10);
    }
  };

  // ===== PAGE 1: HEADER =====
  // Blue header bar
  doc.setFillColor(...BLUE);
  doc.rect(0, 0, pageW, 38, 'F');

  doc.setTextColor(...WHITE);
  doc.setFontSize(22);
  doc.setFont('helvetica', 'bold');
  doc.text('M3 BROS MANAGEMENT', margin, 16);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.text('Financial Report', margin, 24);

  doc.setFontSize(9);
  doc.text(`${branchLabel}  |  ${formatDate(dateRange.start)} - ${formatDate(dateRange.end)}`, margin, 32);

  // Generation timestamp right-aligned
  doc.setFontSize(7);
  doc.text(`Generated: ${new Date().toLocaleString()}`, pageW - margin, 32, { align: 'right' });

  y = 46;

  // ===== FINANCIAL SUMMARY =====
  doc.setTextColor(...DARK);
  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.text('Financial Summary', margin, y);
  y += 2;

  // Divider
  doc.setDrawColor(...BLUE);
  doc.setLineWidth(0.8);
  doc.line(margin, y, margin + 50, y);
  y += 6;

  // Summary cards (5 boxes in a row)
  const cardData = [
    { label: 'Gross Income', value: PHP(reportStats.totalIncome), color: BLUE },
    { label: 'Mgmt Net', value: PHP(reportStats.totalManagementCut), color: GREEN },
    { label: 'Staff Commission', value: PHP(reportStats.totalStaffCut), color: [234, 88, 12] },
    { label: 'Expenses', value: PHP(reportStats.totalExpenses), color: RED },
    { label: 'Transactions', value: String(reportStats.transactionCount), color: [139, 92, 246] },
  ];

  const cardW = (contentW - 4 * 3) / 5; // 3mm gap between cards
  const cardH = 22;

  cardData.forEach((card, i) => {
    const cx = margin + i * (cardW + 3);

    // Card background
    doc.setFillColor(card.color[0], card.color[1], card.color[2]);
    doc.roundedRect(cx, y, cardW, cardH, 2, 2, 'F');

    // Label
    doc.setTextColor(...WHITE);
    doc.setFontSize(7);
    doc.setFont('helvetica', 'normal');
    doc.text(card.label, cx + cardW / 2, y + 8, { align: 'center' });

    // Value
    doc.setFontSize(9);
    doc.setFont('helvetica', 'bold');
    doc.text(card.value, cx + cardW / 2, y + 16, { align: 'center' });
  });

  y += cardH + 8;

  // Net Profit highlight box
  const netProfit = reportStats.totalIncome - reportStats.totalExpenses;
  doc.setFillColor(...LIGHT_BLUE);
  doc.roundedRect(margin, y, contentW, 14, 2, 2, 'F');
  doc.setDrawColor(...BLUE);
  doc.setLineWidth(0.4);
  doc.roundedRect(margin, y, contentW, 14, 2, 2, 'S');

  doc.setTextColor(...DARK);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text('Net Profit (Gross - Expenses):', margin + 4, y + 9);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(netProfit >= 0 ? GREEN[0] : RED[0], netProfit >= 0 ? GREEN[1] : RED[1], netProfit >= 0 ? GREEN[2] : RED[2]);
  doc.text(PHP(netProfit), pageW - margin - 4, y + 9, { align: 'right' });

  y += 22;

  // ===== PAYMENT METHOD BREAKDOWN =====
  doc.setTextColor(...DARK);
  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.text('Payment Method Breakdown', margin, y);
  y += 2;
  doc.setDrawColor(...BLUE);
  doc.setLineWidth(0.8);
  doc.line(margin, y, margin + 60, y);
  y += 4;

  const paymentRows = PAYMENT_MODES.map(mode => {
    const d = paymentMap[mode];
    const pct = paymentGrandTotal > 0 ? ((d.amount / paymentGrandTotal) * 100).toFixed(1) + '%' : '0%';
    return [mode, String(d.count), PHP(d.amount), pct];
  });
  paymentRows.push(['Total', String(filteredTxs.length), PHP(paymentGrandTotal), '100%']);

  autoTable(doc, {
    startY: y,
    head: [['Method', 'Transactions', 'Amount', 'Share']],
    body: paymentRows,
    theme: 'grid',
    margin: { left: margin, right: margin },
    headStyles: { fillColor: BLUE, textColor: WHITE, fontStyle: 'bold', fontSize: 8, halign: 'center' },
    bodyStyles: { fontSize: 8, textColor: DARK },
    columnStyles: {
      0: { halign: 'left', fontStyle: 'bold' },
      1: { halign: 'center' },
      2: { halign: 'right' },
      3: { halign: 'center' },
    },
    didParseCell: (data) => {
      // Style the total row
      if (data.row.index === paymentRows.length - 1) {
        data.cell.styles.fillColor = LIGHT_BLUE;
        data.cell.styles.fontStyle = 'bold';
      }
    },
    alternateRowStyles: { fillColor: LIGHT_GRAY },
  });

  y = doc.lastAutoTable.finalY + 10;

  // ===== STAFF EARNINGS =====
  if (y > pageH - 60) { doc.addPage(); y = margin; }

  doc.setTextColor(...DARK);
  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.text('Staff Earnings', margin, y);
  y += 2;
  doc.setDrawColor(...BLUE);
  doc.setLineWidth(0.8);
  doc.line(margin, y, margin + 40, y);
  y += 4;

  if (staffEarnings.length > 0) {
    const staffRows = staffEarnings.map((s, i) => [String(i + 1), s.name, String(s.count), PHP(s.total)]);
    const staffTotal = staffEarnings.reduce((sum, s) => sum + s.total, 0);
    staffRows.push(['', 'Total', String(staffEarnings.reduce((sum, s) => sum + s.count, 0)), PHP(staffTotal)]);

    autoTable(doc, {
      startY: y,
      head: [['#', 'Staff Name', 'Services', 'Commission']],
      body: staffRows,
      theme: 'grid',
      margin: { left: margin, right: margin },
      headStyles: { fillColor: BLUE, textColor: WHITE, fontStyle: 'bold', fontSize: 8, halign: 'center' },
      bodyStyles: { fontSize: 8, textColor: DARK },
      columnStyles: {
        0: { halign: 'center', cellWidth: 10 },
        1: { halign: 'left', fontStyle: 'bold' },
        2: { halign: 'center' },
        3: { halign: 'right' },
      },
      didParseCell: (data) => {
        if (data.row.index === staffRows.length - 1) {
          data.cell.styles.fillColor = LIGHT_BLUE;
          data.cell.styles.fontStyle = 'bold';
        }
      },
      alternateRowStyles: { fillColor: LIGHT_GRAY },
    });
    y = doc.lastAutoTable.finalY + 10;
  } else {
    doc.setFontSize(9);
    doc.setFont('helvetica', 'italic');
    doc.setTextColor(...GRAY);
    doc.text('No staff earnings for this period.', margin, y + 4);
    y += 12;
  }

  // ===== EXPENSE LEDGER =====
  if (y > pageH - 40) { doc.addPage(); y = margin; }

  const expenseTotal = filteredExpenses.reduce((sum, l) => {
    if (l.action === 'create' || l.action === 'increase') return sum + (l.totalAmount || 0);
    return sum;
  }, 0);

  doc.setTextColor(...DARK);
  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.text(`Expense Ledger (${filteredExpenses.length})`, margin, y);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...RED);
  doc.text(`Total: ${PHP(expenseTotal)}`, pageW - margin, y, { align: 'right' });

  y += 2;
  doc.setDrawColor(...RED);
  doc.setLineWidth(0.8);
  doc.line(margin, y, margin + 40, y);
  y += 4;

  if (filteredExpenses.length > 0) {
    const expRows = filteredExpenses.map(e => [
      e.date,
      e.itemName,
      (e.action || '').toUpperCase(),
      `${e.quantityChange || e.quantity || ''} ${e.unit || ''}`.trim(),
      (e.action === 'create' || e.action === 'increase') && e.totalAmount > 0
        ? PHP(e.totalAmount)
        : '-',
      e.userName || '-',
    ]);

    autoTable(doc, {
      startY: y,
      head: [['Date', 'Item', 'Action', 'Qty', 'Amount', 'By']],
      body: expRows,
      theme: 'grid',
      margin: { left: margin, right: margin },
      headStyles: { fillColor: [185, 28, 28], textColor: WHITE, fontStyle: 'bold', fontSize: 7, halign: 'center' },
      bodyStyles: { fontSize: 7, textColor: DARK },
      columnStyles: {
        0: { cellWidth: 20, halign: 'center' },
        2: { halign: 'center', cellWidth: 18 },
        3: { halign: 'center' },
        4: { halign: 'right', fontStyle: 'bold' },
      },
      alternateRowStyles: { fillColor: [254, 242, 242] },
      showHead: 'everyPage',
    });
    y = doc.lastAutoTable.finalY + 10;
  } else {
    doc.setFontSize(9);
    doc.setFont('helvetica', 'italic');
    doc.setTextColor(...GRAY);
    doc.text('No expenses for this period.', margin, y + 4);
    y += 12;
  }


  // ===== TRANSACTIONS TABLE =====
  if (y > pageH - 40) { doc.addPage(); y = margin; }

  doc.setTextColor(...DARK);
  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.text(`Transactions (${filteredTxs.length})`, margin, y);
  y += 2;
  doc.setDrawColor(...BLUE);
  doc.setLineWidth(0.8);
  doc.line(margin, y, margin + 40, y);
  y += 4;

  if (filteredTxs.length > 0) {
    const txRows = filteredTxs.slice(0, 100).map(t => {
      const row = [
        t.date,
        t.service,
        t.staff,
        t.paymentMode,
        PHP(t.price),
      ];
      if (isAll) row.splice(1, 0, BRANCHES[t.branch]?.name?.replace('M3 Bros ', '') || t.branch);
      return row;
    });

    const txHead = ['Date', 'Service', 'Staff', 'Payment', 'Price'];
    if (isAll) txHead.splice(1, 0, 'Branch');

    autoTable(doc, {
      startY: y,
      head: [txHead],
      body: txRows,
      theme: 'grid',
      margin: { left: margin, right: margin },
      headStyles: { fillColor: BLUE, textColor: WHITE, fontStyle: 'bold', fontSize: 7, halign: 'center' },
      bodyStyles: { fontSize: 7, textColor: DARK },
      columnStyles: {
        0: { cellWidth: 20, halign: 'center' },
        [txHead.length - 1]: { halign: 'right', fontStyle: 'bold' },
        [txHead.length - 2]: { halign: 'center' },
      },
      alternateRowStyles: { fillColor: LIGHT_GRAY },
      showHead: 'everyPage',
    });
    y = doc.lastAutoTable.finalY + 10;
  } else {
    doc.setFontSize(9);
    doc.setFont('helvetica', 'italic');
    doc.setTextColor(...GRAY);
    doc.text('No transactions for this period.', margin, y + 4);
    y += 12;
  }

  // ===== ADD FOOTERS TO ALL PAGES =====
  addFooter();

  // ===== SAVE =====
  const filename = isAll
    ? `M3Bros_Report_AllBranches_${dateRange.start}_to_${dateRange.end}.pdf`
    : `M3Bros_Report_${exportBranch}_${dateRange.start}_to_${dateRange.end}.pdf`;
  doc.save(filename);
}
